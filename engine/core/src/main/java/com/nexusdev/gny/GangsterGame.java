package com.nexusdev.gny;

import com.badlogic.gdx.*;
import com.badlogic.gdx.graphics.*;
import com.badlogic.gdx.graphics.g2d.*;
import com.badlogic.gdx.graphics.g3d.*;
import com.badlogic.gdx.graphics.g3d.attributes.ColorAttribute;
import com.badlogic.gdx.graphics.g3d.environment.DirectionalLight;
import com.badlogic.gdx.graphics.g3d.loader.ObjLoader;
import com.badlogic.gdx.graphics.g3d.utils.*;
import com.badlogic.gdx.graphics.glutils.ShapeRenderer;
import com.badlogic.gdx.math.*;
import com.badlogic.gdx.utils.Array;
import com.badlogic.gdx.utils.ScreenUtils;

/** Early Android 3D prototype. Original OBJ models are generated by tools/generate_models.py. */
public class GangsterGame extends ApplicationAdapter {
 private PerspectiveCamera camera;
 private OrthographicCamera hudCamera;
 private ModelBatch batch;
 private Environment lighting;
 private ShapeRenderer shapes;
 private SpriteBatch sprites;
 private BitmapFont font;
 private final Array<ModelInstance> city=new Array<>();
 private final Array<Model> models=new Array<>();
 private Model carModel,playerModel,treeModel,lampModel,low,mid,tower,warehouse;
 private Model road,sidewalk,ground,line,park;
 private ModelInstance car,player;
 private float px=0,pz=0,heading=0,cx=3.2f,cz=-2,carHeading=0,carSpeed=0,yaw=.15f;
 private float moveX,moveY,lastX;
 private int movePointer=-1,lookPointer=-1;
 private boolean driving=false,missionDone=false;
 private int cash=250;
 private static final float LIMIT=250;

 @Override public void create(){
  batch=new ModelBatch(); shapes=new ShapeRenderer(); sprites=new SpriteBatch(); font=new BitmapFont();
  font.getData().setScale(1.2f);
  hudCamera=new OrthographicCamera(Gdx.graphics.getWidth(),Gdx.graphics.getHeight()); hudCamera.setToOrtho(false);
  lighting=new Environment();
  lighting.set(new ColorAttribute(ColorAttribute.AmbientLight,.68f,.70f,.74f,1));
  lighting.add(new DirectionalLight().set(.92f,.88f,.80f,-.45f,-1,-.25f));
  camera=new PerspectiveCamera(68,Gdx.graphics.getWidth(),Gdx.graphics.getHeight());
  camera.near=.1f; camera.far=650;
  loadModels(); buildDistrict();
  player=new ModelInstance(playerModel); player.transform.setToTranslation(px,1.03f,pz);
  car=new ModelInstance(carModel); car.transform.setToTranslation(cx,0,cz).rotate(Vector3.Y,carHeading*MathUtils.radiansToDegrees); updateCamera();
  Gdx.input.setCatchKey(Input.Keys.BACK,true); Gdx.input.setInputProcessor(new Controls());
 }

 private Model box(float w,float h,float d,Color c){
  Model m=new ModelBuilder().createBox(w,h,d,VertexAttributes.Usage.Position|VertexAttributes.Usage.Normal,
      new Material(ColorAttribute.createDiffuse(c)));
  models.add(m); return m;
 }
 private Model obj(String path,Model fallback){
  try{ Model m=new ObjLoader().loadModel(Gdx.files.internal(path)); models.add(m); return m; }
  catch(Exception e){ Gdx.app.error("GNY","OBJ load failed: "+path,e); return fallback; }
 }
 private void loadModels(){
  Model personFallback=box(.7f,1.9f,.45f,new Color(.08f,.18f,.38f,1));
  Model carFallback=box(1.9f,1.1f,4.1f,new Color(.1f,.24f,.48f,1));
  playerModel=obj("models/carl_lowpoly.obj",personFallback);
  carModel=obj("models/sedan_blue.obj",carFallback);
  treeModel=obj("models/street_tree.obj",box(1.2f,4,1.2f,new Color(.12f,.34f,.16f,1)));
  lampModel=obj("models/streetlight.obj",box(.18f,5,.18f,Color.DARK_GRAY));
  low=obj("models/building_low.obj",box(12,10,12,new Color(.48f,.30f,.22f,1)));
  mid=obj("models/building_mid.obj",box(12,24,12,new Color(.42f,.46f,.5f,1)));
  tower=obj("models/building_tower.obj",box(13,48,13,new Color(.32f,.38f,.46f,1)));
  warehouse=obj("models/warehouse.obj",box(20,9,14,new Color(.4f,.25f,.19f,1)));
  ground=box(620,.25f,620,new Color(.20f,.27f,.22f,1));
  road=box(620,.12f,13,new Color(.105f,.115f,.13f,1));
  sidewalk=box(620,.18f,2.2f,new Color(.43f,.43f,.41f,1));
  line=box(620,.025f,.16f,new Color(.86f,.77f,.46f,1));
  park=box(38,.16f,38,new Color(.13f,.31f,.16f,1));
 }
 private void add(Model m,float x,float y,float z){
  ModelInstance i=new ModelInstance(m); i.transform.setToTranslation(x,y,z); city.add(i);
 }
 private void buildDistrict(){
  add(ground,0,-.22f,0);
  for(int n=-6;n<=6;n++){
   float p=n*38;
   add(road,0,-.035f,p); add(sidewalk,0,.035f,p-7.6f); add(sidewalk,0,.035f,p+7.6f); add(line,0,.04f,p);
   ModelInstance v=new ModelInstance(road); v.transform.setToTranslation(p,-.035f,0).rotate(Vector3.Y,90); city.add(v);
   ModelInstance a=new ModelInstance(sidewalk); a.transform.setToTranslation(p-7.6f,.035f,0).rotate(Vector3.Y,90); city.add(a);
   ModelInstance b=new ModelInstance(sidewalk); b.transform.setToTranslation(p+7.6f,.035f,0).rotate(Vector3.Y,90); city.add(b);
  }
  for(int x=-5;x<=5;x++) for(int z=-5;z<=5;z++){
   if(Math.abs(x)<=1&&Math.abs(z)<=1)continue;
   float bx=x*38+(x%2==0?9:-9),bz=z*38+(z%2==0?9:-9);
   int v=Math.abs(x*7+z*11)%12;
   add(v==0?warehouse:v<4?low:v<9?mid:tower,bx,0,bz);
   if(v%3==0)add(low,bx+9,0,bz+10);
  }
  add(park,0,.02f,0);
  for(int i=0;i<10;i++){float a=i*MathUtils.PI2/10;add(treeModel,MathUtils.cos(a)*15,0,MathUtils.sin(a)*15);}
  for(int i=-5;i<=5;i++)if(i!=0){
   float p=i*38; add(treeModel,-10.5f,0,p+8); add(treeModel,10.5f,0,p-8);
   add(lampModel,-9.8f,0,p-10); add(lampModel,9.8f,0,p+10);
  }
  for(int i=0;i<12;i++){
   ModelInstance npc=new ModelInstance(playerModel);
   npc.transform.setToTranslation(13+(i%4-1.5f)*3.2f,1.02f,-4+(i/4-1)*4);
   city.add(npc);
  }
 }
 private void updateCamera(){
  float x=driving?cx:px,z=driving?cz:pz;
  float dist=driving?10.5f:7.5f,height=driving?5:4.1f;
  camera.position.set(x+MathUtils.sin(yaw)*dist,height+(driving?1:1.1f),z+MathUtils.cos(yaw)*dist);
  camera.lookAt(x,driving?1.2f:1.3f,z); camera.up.set(Vector3.Y); camera.update();
 }
 private void update(float dt){
  if(driving){
   carHeading-=moveX*dt*(1.5f+Math.abs(carSpeed)*.1f);
   carSpeed=MathUtils.clamp((carSpeed+moveY*dt*13)*(1-dt*1.15f),-8,25);
   cx=MathUtils.clamp(cx+MathUtils.sin(carHeading)*carSpeed*dt,-LIMIT,LIMIT);
   cz=MathUtils.clamp(cz-MathUtils.cos(carHeading)*carSpeed*dt,-LIMIT,LIMIT);
   car.transform.setToTranslation(cx,0,cz).rotate(Vector3.Y,carHeading*MathUtils.radiansToDegrees);
   yaw=MathUtils.lerpAngle(yaw,carHeading,Math.min(1,dt*2.2f));
  }else{
   float len=(float)Math.sqrt(moveX*moveX+moveY*moveY),sx=moveX,sy=moveY;
   if(len>1){sx/=len;sy/=len;}
   float dx=(MathUtils.sin(yaw)*sy+MathUtils.cos(yaw)*sx)*5.4f*dt;
   float dz=(-MathUtils.cos(yaw)*sy+MathUtils.sin(yaw)*sx)*5.4f*dt;
   px=MathUtils.clamp(px+dx,-LIMIT,LIMIT); pz=MathUtils.clamp(pz+dz,-LIMIT,LIMIT);
   if(len>.12f)heading=(float)Math.atan2(dx,-dz);
   player.transform.setToTranslation(px,1.03f,pz).rotate(Vector3.Y,heading*MathUtils.radiansToDegrees);
  }
  updateCamera();
 }
 private boolean nearCar(){float x=px-cx,z=pz-cz;return x*x+z*z<25;}
 private void action(){
  if(driving){driving=false;px=cx+2.2f;pz=cz;heading=carHeading;carSpeed=0;
   player.transform.setToTranslation(px,1.03f,pz).rotate(Vector3.Y,heading*MathUtils.radiansToDegrees);
  }else if(nearCar()){driving=true;carSpeed=0;yaw=carHeading;if(!missionDone){missionDone=true;cash+=250;}}
 }
 private void hud(){
  float w=Gdx.graphics.getWidth(),h=Gdx.graphics.getHeight();
  hudCamera.setToOrtho(false,w,h); shapes.setProjectionMatrix(hudCamera.combined);
  Gdx.gl.glEnable(GL20.GL_BLEND); Gdx.gl.glBlendFunc(GL20.GL_SRC_ALPHA,GL20.GL_ONE_MINUS_SRC_ALPHA);
  shapes.begin(ShapeRenderer.ShapeType.Filled);
  shapes.setColor(0,0,0,.28f);shapes.circle(112,112,76);
  shapes.setColor(.85f,.88f,.92f,.42f);shapes.circle(112+moveX*34,112+moveY*34,29);
  shapes.setColor(.05f,.08f,.12f,.68f);shapes.circle(w-115,118,66);
  shapes.setColor(.25f,.60f,.88f,.75f);shapes.circle(w-115,118,55);shapes.end();
  sprites.setProjectionMatrix(hudCamera.combined);sprites.begin();font.setColor(Color.WHITE);
  font.draw(sprites,"GANGSTER: NEW YORK",28,h-26);
  font.draw(sprites,driving?"BROOKLYN | VEHICLE":"NEW YORK | BROOKLYN",28,h-52);
  font.draw(sprites,driving?("SPEED "+(int)(Math.abs(carSpeed)*7)+" | CASH $"+cash):(missionDone?"MISSION COMPLETE | CASH $"+cash:"MISSION 01 | FIND YOUR CAR"),28,h-78);
  if(driving||nearCar())font.draw(sprites,driving?"EXIT":"DRIVE",w-143,123);
  font.draw(sprites,"MOVE",82,25);font.draw(sprites,"SWIPE RIGHT TO LOOK",w*.48f,30);
  sprites.end();Gdx.gl.glDisable(GL20.GL_BLEND);
 }
 @Override public void render(){
  float dt=Math.min(Gdx.graphics.getDeltaTime(),.04f);update(dt);
  ScreenUtils.clear(.47f,.66f,.80f,1,true);Gdx.gl.glEnable(GL20.GL_DEPTH_TEST);
  batch.begin(camera);for(ModelInstance i:city)batch.render(i,lighting);
  if(!driving)batch.render(player,lighting);batch.render(car,lighting);batch.end();hud();
 }
 @Override public void resize(int w,int h){camera.viewportWidth=w;camera.viewportHeight=h;camera.update();hudCamera.setToOrtho(false,w,h);}
 @Override public void dispose(){batch.dispose();shapes.dispose();sprites.dispose();font.dispose();for(Model m:models)m.dispose();}

 private class Controls extends InputAdapter{
  @Override public boolean touchDown(int sx,int sy,int pointer,int button){
   float x=sx,y=Gdx.graphics.getHeight()-sy,w=Gdx.graphics.getWidth(),h=Gdx.graphics.getHeight();
   if(x>w*.78f&&y<h*.34f){action();return true;}
   if(x<w*.34f&&y<h*.38f){movePointer=pointer;joystick(x,y);return true;}
   if(x>w*.4f){lookPointer=pointer;lastX=x;return true;}return true;
  }
  @Override public boolean touchDragged(int sx,int sy,int pointer){
   float x=sx,y=Gdx.graphics.getHeight()-sy;
   if(pointer==movePointer)joystick(x,y);
   else if(pointer==lookPointer){yaw-=(x-lastX)*.006f;lastX=x;if(driving)carHeading=MathUtils.lerpAngle(carHeading,yaw,.1f);}
   return true;
  }
  @Override public boolean touchUp(int x,int y,int pointer,int button){
   if(pointer==movePointer){movePointer=-1;moveX=moveY=0;}if(pointer==lookPointer)lookPointer=-1;return true;
  }
  private void joystick(float x,float y){moveX=MathUtils.clamp((x-112)/70,-1,1);moveY=MathUtils.clamp((y-112)/70,-1,1);}
  @Override public boolean keyDown(int key){if(key==Input.Keys.E||key==Input.Keys.ENTER)action();return true;}
 }
}